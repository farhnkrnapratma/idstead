<script lang="ts">
    import { onMount } from 'svelte';
    import {
        CONTENT_LICENSES,
        CONTENT_LICENSE_INFO,
        type ContentLicenseId,
        type ContentLicenseSettings
    } from '@idstead/domain/contentLicense.ts';
    import Button from '@idstead/ui/components/Button.svelte';
    import Card from '@idstead/ui/components/Card.svelte';
    import Dropdown from '@idstead/ui/components/Dropdown.svelte';
    import ErrorState from '@idstead/ui/components/ErrorState.svelte';
    import FieldMessage from '@idstead/ui/components/FieldMessage.svelte';
    import LoadingState from '@idstead/ui/components/LoadingState.svelte';
    import StatusBanner from '@idstead/ui/components/StatusBanner.svelte';
    import FormSection from '@idstead/ui/layout/FormSection.svelte';
    import { toastStore } from '@idstead/ui/stores/toastStore.svelte.ts';
    import { adminFetch, adminRequest } from '#app/adminClient.ts';

    const licenseOptions = CONTENT_LICENSES.map(value => ({
        value,
        label: CONTENT_LICENSE_INFO[value].label
    }));

    let loading = $state(true);
    let loadError = $state('');
    let saving = $state(false);
    let license = $state<ContentLicenseId>('all-rights-reserved');
    let fieldError = $state('');

    const info = $derived(CONTENT_LICENSE_INFO[license]);

    async function load() {
        loading = true;
        loadError = '';
        try {
            license = (
                await adminRequest<{ contentLicense: ContentLicenseSettings }>(
                    'site-settings/content-license'
                )
            ).contentLicense.license;
        } catch (error) {
            loadError = error instanceof Error ? error.message : 'Could not load the settings.';
        } finally {
            loading = false;
        }
    }

    onMount(() => {
        void load();
    });

    function setLicense(value: ContentLicenseId) {
        license = value;
        fieldError = '';
    }

    async function save(event: SubmitEvent) {
        event.preventDefault();
        if (saving) return;
        saving = true;
        fieldError = '';
        try {
            const response = await adminFetch('/api/internal/admin/site-settings/content-license', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ license })
            });
            const result = await response.json().catch(() => null);
            if (response.ok && result?.contentLicense) {
                license = result.contentLicense.license;
                toastStore.success('Content license saved.');
                return;
            }
            fieldError = result?.error?.message ?? 'The settings could not be saved.';
        } catch (error) {
            fieldError =
                error instanceof Error ? error.message : 'The settings could not be saved.';
        } finally {
            saving = false;
        }
    }
</script>

<FormSection
    title="Content license"
    titleClass="type-card-title"
    description="Choose the license for your posts, banners and other content. The site footer and every post show it, and a post can override it in the editor."
    onsubmit={save}
    bare>
    {#if loading}
        <LoadingState
            variant="spinner"
            label="Loading content license..." />
    {:else if loadError}
        <ErrorState
            title="Couldn't load the content license"
            description={loadError}
            onRetry={load} />
    {:else}
        <div class="flex max-w-lg flex-col gap-4">
            <Dropdown
                id="content-license"
                label="License"
                value={license}
                options={licenseOptions}
                fullWidth
                onChange={setLicense} />
            {#if fieldError}<FieldMessage message={fieldError} />{/if}
            <Card
                variant="bordered"
                density="compact"
                class="border-line-subtle! bg-surface!">
                <p class="type-body text-fg-secondary">
                    {#if info.url}
                        Visitors may reuse your content under the {info.name} license.
                    {:else}
                        Visitors may not reuse your content without your permission.
                    {/if}
                </p>
            </Card>
            <StatusBanner
                variant="info"
                title="License only what you own"
                message="Banners and images from someone else or generated by AI keep their own terms. Credit them in the post editor so the site license does not claim them." />
        </div>
    {/if}
    {#snippet actions()}
        <Button
            htmlType="submit"
            size="md"
            isLoading={saving}
            disabled={saving || loading || !!loadError}>Save</Button>
    {/snippet}
</FormSection>
