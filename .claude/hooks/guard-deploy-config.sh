#!/usr/bin/env bash
jq -r '.tool_input.file_path // empty' | {
  read -r f
  [ -z "$f" ] && { echo '{}'; exit 0; }
  rel=${f#"$PWD"/}
  decision=""
  reason=""
  if [[ "$rel" =~ ^apps/[^/]+/wrangler\.jsonc$ ]]; then
    decision="deny"
    reason="$rel is generated by bun run configure from idstead.jsonc and apps/<app>/wrangler.template.jsonc. Edit those and run bun run configure instead."
  elif [ "$rel" = "idstead.jsonc" ] || [[ "$rel" =~ ^apps/[^/]+/wrangler\.template\.jsonc$ ]]; then
    decision="ask"
    reason="$rel sets the live Workers, bindings, routes and crons once rendered by bun run configure. Confirm this edit is intentional."
  elif [[ "$rel" =~ ^\.github/workflows/[^/]+\.ya?ml$ ]]; then
    decision="ask"
    reason="$rel runs Claude Code on GitHub with the CLAUDE_CODE_OAUTH_TOKEN secret. Confirm this edit is intentional."
  fi
  if [ -n "$decision" ]; then
    jq -n --arg d "$decision" --arg reason "$reason" '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":$d,"permissionDecisionReason":$reason}}'
  else
    echo '{}'
  fi
}
